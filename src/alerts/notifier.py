"""
Alert Notifier: Formats Early Warning Reports and Sentinel Briefings
Supports Console (Rich), Markdown Artifacts, and Webhook payloads.
"""
from typing import List
from datetime import datetime
from src.models.portfolio import UnifiedPortfolio, AdverseEvent, SeverityLevel


class AlertNotifier:
    """
    Renders structured notifications and briefings for portfolio risk management.
    """

    @staticmethod
    def generate_markdown_report(portfolio: UnifiedPortfolio, events: List[AdverseEvent]) -> str:
        """
        Generates an executive markdown risk report suitable for saving or sending via Telegram/Discord.
        """
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S IST")
        lines = []
        lines.append(f"# 🛡️ Indian Portfolio Sentinel: Risk & Adverse Event Briefing")
        lines.append(f"*Generated: {now_str} | Coverage: Zerodha Kite, Groww, INDmoney*\n")

        # Portfolio Summary Table
        lines.append("## 📊 Consolidated Portfolio Health")
        lines.append(f"- **Total Current Value**: ₹{portfolio.total_current_value:,.2f}")
        lines.append(f"- **Total Invested**: ₹{portfolio.total_invested:,.2f}")
        lines.append(f"- **Unrealized P&L**: ₹{portfolio.total_pnl:,.2f} ({portfolio.total_pnl_pct:+.2f}%)")
        lines.append(f"- **Cash Buffer**: ₹{portfolio.cash_balance:,.2f} ({(portfolio.cash_balance / portfolio.total_net_worth * 100):.1f}%)\n")

        lines.append("| Symbol | Asset Type | Broker | Qty | Avg Price | Current Price | P&L % | Weight % |")
        lines.append("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
        for h in portfolio.holdings:
            pnl_sign = "+" if h.pnl >= 0 else ""
            lines.append(
                f"| **{h.symbol}** | {h.asset_type.value} | {h.broker.value} | {h.quantity:,.1f} | "
                f"₹{h.average_price:,.2f} | ₹{h.current_price:,.2f} | {pnl_sign}{h.pnl_pct:.1f}% | {h.weight_pct:.1f}% |"
            )

        lines.append("\n---\n")

        # Adverse Events Section
        lines.append("## 🚨 Adverse Market Events & Early Warning Triggers")
        if not events:
            lines.append("✅ **All Clear**: No adverse regulatory, corporate filing, news, or technical alerts detected across your holdings.")
        else:
            lines.append(f"Found **{len(events)}** active warnings across your held assets:\n")
            for idx, ev in enumerate(events, 1):
                severity_badge = {
                    SeverityLevel.CRITICAL: "🔴 **CRITICAL**",
                    SeverityLevel.HIGH: "🟠 **HIGH RISK**",
                    SeverityLevel.MEDIUM: "🟡 **MEDIUM CONCERN**",
                    SeverityLevel.LOW: "🔵 **LOW / MONITOR**",
                    SeverityLevel.NEUTRAL: "⚪ **NEUTRAL**"
                }.get(ev.severity, "⚠️")

                lines.append(f"### {idx}. {severity_badge}: {ev.symbol} - {ev.headline}")
                lines.append(f"- **Category**: `{ev.category}` | **Source**: {ev.source}")
                lines.append(f"- **Diagnosis**: {ev.summary}")
                lines.append(f"- **Actionable Guidance**: `{ev.recommended_action}`")
                if ev.url:
                    lines.append(f"- **Reference Link**: [{ev.source}]({ev.url})")
                lines.append("")

        lines.append("\n---\n")
        lines.append("> *Disclaimer: Generated by Antigravity Sentinel. Non-day-trading, delivery-focused research model. Verify exchange filings before order placement.*")
        return "\n".join(lines)

    @staticmethod
    def print_terminal_summary(portfolio: UnifiedPortfolio, events: List[AdverseEvent]):
        """Prints a human-readable clean terminal summary."""
        import sys
        if hasattr(sys.stdout, "reconfigure"):
            try:
                sys.stdout.reconfigure(encoding="utf-8", errors="replace")
            except Exception:
                pass

        print("=" * 80)
        print("[SENTINEL] INDIAN PORTFOLIO SENTINEL - ADVERSE EVENT RADAR")
        print("=" * 80)
        print(f"Total Net Worth: Rs. {portfolio.total_net_worth:,.2f} | Invested: Rs. {portfolio.total_invested:,.2f} | P&L: Rs. {portfolio.total_pnl:,.2f} ({portfolio.total_pnl_pct:+.2f}%)")
        print(f"Holdings Monitored: {len(portfolio.holdings)} assets across Kite, Groww, INDmoney")
        print("-" * 80)

        if not events:
            print("[OK] All clear. No adverse events detected.")
        else:
            print(f"[ALERT] {len(events)} ADVERSE EVENTS / HEADS-UP NOTICES DETECTED:")
            for ev in events:
                print(f" [{ev.severity.value}] {ev.symbol:<12} | {ev.category:<22} | Action: {ev.recommended_action}")
                print(f"   -> {ev.headline}")
                print(f"   -> Summary: {ev.summary[:100]}...")
                print()
        print("=" * 80)
